    /**
     * Checks if a MAC address has the locally administered / randomized bit set (bit 1 of first byte).
     * Standard IEEE 802: If (byte0 & 0x02) != 0, it is a Locally Administered Address (LAA / Randomized).
     */
    fun isLocallyAdministeredOrRandomized(mac: String?): Boolean {
        if (mac.isNullOrBlank()) return false
        val clean = mac.replace(":", "").replace("-", "").trim()
        if (clean.length < 2) return false
        val firstByte = clean.substring(0, 2).toIntOrNull(16) ?: return false
        // Bit 1 (0x02) indicates locally administered (randomized) address
        return (firstByte and 0x02) != 0
    }

    /**
     * Resolves vendor information from hardware MAC address with strict randomization detection.
     */
    fun resolveVendorFromMac(mac: String?): VendorResolution {
        if (mac.isNullOrBlank()) {
            return VendorResolution(
                vendor = null,
                normalizedVendor = null,
                isRandomizedMac = false,
                confidence = ConfidenceLevel.NONE,
                source = IdentitySource.UNKNOWN
            )
        }

        val cleanMac = mac.replace(":", "").replace("-", "").trim().uppercase()
        if (cleanMac.length < 6) {
            return VendorResolution(
                vendor = null,
                normalizedVendor = null,
                isRandomizedMac = false,
                confidence = ConfidenceLevel.NONE,
                source = IdentitySource.UNKNOWN
            )
        }

        val isRandomized = isLocallyAdministeredOrRandomized(cleanMac)
        if (isRandomized) {
            return VendorResolution(
                vendor = "Randomized MAC (Privacy Address)",
                normalizedVendor = "Randomized (Privacy)",
                isRandomizedMac = true,
                confidence = ConfidenceLevel.LOW,
                source = IdentitySource.MAC_OUI
            )
        }

        val prefix = cleanMac.substring(0, 6)
        val rawVendor = OUI_DATABASE[prefix]

        if (rawVendor != null) {
            val normalized = normalizeVendor(rawVendor)
            return VendorResolution(
                vendor = rawVendor,
                normalizedVendor = normalized,
                isRandomizedMac = false,
                confidence = ConfidenceLevel.HIGH,
                source = IdentitySource.MAC_OUI
            )
        }

        return VendorResolution(
            vendor = null,
            normalizedVendor = null,
            isRandomizedMac = false,
            confidence = ConfidenceLevel.NONE,
            source = IdentitySource.UNKNOWN
        )
    }

    /**
