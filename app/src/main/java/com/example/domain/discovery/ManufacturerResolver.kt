            clean.contains("Espressif", ignoreCase = true) -> "Espressif"
            clean.contains("NVIDIA", ignoreCase = true) -> "NVIDIA"
            clean.contains("VMware", ignoreCase = true) -> "VMware"
            clean.contains("Cisco", ignoreCase = true) -> "Cisco"
            clean.contains("Asus", ignoreCase = true) -> "ASUS"
            clean.contains("Netgear", ignoreCase = true) -> "Netgear"
            clean.contains("D-Link", ignoreCase = true) -> "D-Link"
            clean.contains("Linksys", ignoreCase = true) -> "Linksys"
            clean.contains("HP", ignoreCase = true) || clean.contains("Hewlett", ignoreCase = true) -> "HP"
